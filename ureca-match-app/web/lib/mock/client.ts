/** Reference lists, same as services/catalog.py (generated by app.db.export). */
const catalog = catalogJson as unknown as { topics: M.TopicGroup[]; courses: M.Course[] };
const topicByLower = new Map(catalog.topics.flatMap((g) => g.topics.map((t) => [t.toLowerCase(), t] as const)));
const courseCodes = new Set(catalog.courses.map((c) => c.code));
const courseCode = (t: string) => t.replace(/\s+/g, "").toUpperCase();
function cleanTopics(values: string[], field: string) {
  const out: string[] = [];
  for (const v of values) {
    const t = topicByLower.get(v.trim().toLowerCase());
    if (!t) throw new M.ApiError(422, "unknown_topic", `"${v.trim()}" is not a standard topic. Choose one from the list.`, field);
    if (!out.includes(t)) out.push(t);
  }
  return out;
}
function cleanCourses(values: string[], field: string) {
  const out: string[] = [];
  for (const v of values) {
    const c = courseCode(v);
    if (!courseCodes.has(c)) throw new M.ApiError(422, "unknown_course", `"${v.trim()}" is not an NTU course code. Choose one from the list.`, field);
    if (!out.includes(c)) out.push(c);
  }
  return out;
}

