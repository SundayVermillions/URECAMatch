"""Export the contract and the demo data.

  uv run python -m app.db.export

Writes  ../shared/openapi.json          (API contract; web runs `npm run gen` on it)
        ../web/lib/mock/seed.json       (web mock mode data)
        ../web/lib/mock/catalog.json    (topics and NTU courses for mock mode pickers)
        ../supabase/catalog.sql         (the same reference lists for a real database)
        ../supabase/seed.sql            (demo rows for a real database)
"""

from __future__ import annotations

import json
from pathlib import Path

from app.db import seed_data
from app.main import app
from app.services import catalog

ROOT = Path(__file__).resolve().parents[3]


def _dump(v):
    return json.loads(v.model_dump_json()) if hasattr(v, "model_dump_json") else v


def main() -> None:
    (ROOT / "shared").mkdir(exist_ok=True)
    (ROOT / "shared" / "openapi.json").write_text(json.dumps(app.openapi(), indent=2))

    data = seed_data.build()
    seed = {k: (_dump(v) if not isinstance(v, list) else [_dump(x) for x in v]) for k, v in data.items()}
    seed["applicant_rankings"] = {
        "lst-1:rnd-2": [a.id for a in data["applications"] if a.listing_id == "lst-1" and a.round_id == "rnd-2"][:4]
    }
    out = ROOT / "web" / "lib" / "mock" / "seed.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(seed, indent=2))

    groups = [g.model_dump() for g in catalog.topic_groups()]
    courses = [c.model_dump() for c in catalog.courses().values()]
    (out.parent / "catalog.json").write_text(json.dumps({"topics": groups, "courses": courses}))

    (ROOT / "supabase" / "seed.sql").write_text(_seed_sql(data))
    (ROOT / "supabase" / "catalog.sql").write_text(_catalog_sql(groups, courses))
    print("wrote shared/openapi.json, web/lib/mock/seed.json, web/lib/mock/catalog.json, supabase/seed.sql, supabase/catalog.sql")


def _sql(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int | float):
        return str(v)
    if isinstance(v, list):
        return "array[" + ",".join(_sql(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    if hasattr(v, "isoformat"):
        return f"'{v.isoformat()}'"
    if hasattr(v, "value"):
        return f"'{v.value}'"
    return "'" + str(v).replace("'", "''") + "'"


def _rows(table: str, cols: list[str], rows: list[dict]) -> str:
    if not rows:
        return ""
    vals = ",\n".join("(" + ", ".join(_sql(r.get(c)) for c in cols) + ")" for r in rows)
    return f"insert into {table} ({', '.join(cols)}) values\n{vals}\non conflict (id) do nothing;\n\n"


def _seed_sql(d: dict) -> str:
    out = ["-- Generated by `python -m app.db.export`. Do not edit by hand.\nbegin;\n\n"]
    out.append(_rows("users", ["id", "email", "name", "role", "status", "created_at"], [u.model_dump() for u in d["users"]]))
    out.append(
        _rows(
            "student_profiles",
            [
                "user_id",
                "school",
                "cgpa",
                "year_of_study",
                "completed_modules",
                "research_interests",
                "profile_complete",
                "eligible_for_matching",
            ],
            [s.model_dump() for s in d["students"]],
        ).replace("on conflict (id)", "on conflict (user_id)")
    )
    out.append(
        _rows(
            "supervisor_profiles", ["user_id", "faculty", "organisation", "title"], [s.model_dump() for s in d["supervisors"]]
        ).replace("on conflict (id)", "on conflict (user_id)")
    )
    docs = [doc.model_dump() for s in d["students"] for doc in s.documents]
    out.append(
        _rows("supporting_documents", ["id", "owner_id", "file_name", "file_format", "kind", "file_size", "uploaded_at"], docs)
    )
    c = d["cycle"]
    out.append(
        _rows(
            "application_cycles",
            ["id", "academic_year", "opening_date", "closing_date", "pre_application_days", "status"],
            [c.model_dump(exclude={"rounds"})],
        )
    )
    out.append(
        _rows(
            "matching_rounds",
            [
                "id",
                "cycle_id",
                "number",
                "application_start",
                "application_end",
                "review_start",
                "review_end",
                "approval_end",
                "status",
                "executed_at",
                "published_at",
            ],
            [r.model_dump() for r in c.rounds],
        )
    )
    out.append(
        _rows(
            "project_listings",
            [
                "id",
                "supervisor_id",
                "title",
                "description",
                "prerequisites",
                "topic_tags",
                "available_slots",
                "filled_slots",
                "offering_faculty",
                "research_location",
                "cover_url",
                "outcomes",
                "skills",
                "hours_per_week",
                "mode",
                "gallery_urls",
                "video_url",
                "status",
                "created_at",
            ],
            [lst.model_dump() for lst in d["listings"]],
        )
    )
    out.append(
        _rows(
            "listing_applications",
            [
                "id",
                "student_id",
                "listing_id",
                "round_id",
                "statement",
                "submitted_at",
                "preference_rank",
                "status",
                "document_ids",
            ],
            [a.model_dump() for a in d["applications"]],
        )
    )
    out.append(
        _rows(
            "self_proposed_applications",
            [
                "id",
                "student_id",
                "supervisor_id",
                "title",
                "description",
                "research_interests",
                "statement",
                "status",
                "submitted_at",
                "decided_at",
                "decision_note",
                "document_ids",
            ],
            [p.model_dump() for p in d["proposals"]],
        )
    )
    out.append(
        _rows(
            "match_results",
            [
                "id",
                "round_id",
                "student_id",
                "listing_id",
                "status",
                "preference_rank",
                "supervisor_decided_at",
                "published_at",
                "offer_expires_at",
                "student_responded_at",
                "original_listing_id",
                "justification",
            ],
            [m.model_dump() for m in d["matches"]],
        )
    )
    out.append(
        _rows(
            "notifications",
            ["id", "user_id", "event", "title", "message", "created_at", "read", "link"],
            [n.model_dump() for n in d["notifications"]],
        )
    )
    out.append(
        _rows(
            "conversations",
            ["id", "student_id", "supervisor_id", "created_at", "last_message_at"],
            [c.model_dump() for c in d["conversations"]],
        )
    )
    out.append(
        _rows(
            "messages",
            ["id", "conversation_id", "sender_id", "body", "created_at", "read"],
            [m.model_dump() for m in d["messages"]],
        )
    )
    out.append(
        _rows(
            "audit_log",
            ["id", "operation", "actor_id", "timestamp", "affected_records", "note"],
            [a.model_dump() for a in d["audit"]],
        )
    )
    out.append("commit;\n")
    return "".join(out)


def _catalog_sql(groups: list[dict], courses: list[dict]) -> str:
    """Reference lists. Re-running refreshes titles, so a new scrape can be applied over old rows."""
    topics = [{"name": t, "topic_group": g["name"]} for g in groups for t in g["topics"]]
    cols = ["code", "title", "au", "dept", "last_offered"]
    refresh = ", ".join(f"{c} = excluded.{c}" for c in cols[1:])
    return (
        "-- Generated by `python -m app.db.export`. Do not edit by hand. Safe to run again: it refreshes the lists.\nbegin;\n\n"
        + _rows("topics", ["name", "topic_group"], topics).replace(
            "on conflict (id) do nothing", "on conflict (name) do update set topic_group = excluded.topic_group"
        )
        + _rows("courses", cols, courses).replace("on conflict (id) do nothing", f"on conflict (code) do update set {refresh}")
        + "commit;\n"
    )


if __name__ == "__main__":
    main()
